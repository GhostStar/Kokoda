#!/usr/bin/env python3
"""Generate native resources from the shared bilingual catalogs; --check detects drift."""
import json,re,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
catalogs={lang:json.loads((root/f'apps/desktop/locales/{lang}.json').read_text(encoding='utf-8')) for lang in ['en','zh-CN']}
if set(catalogs['en']) != set(catalogs['zh-CN']):raise SystemExit('Locale keys differ')
used=set()
for base in ['apps/macos','platforms/macos']:
 for file in (root/base).rglob('*.swift'):
  used.update(re.findall(r'(?:L|NSLocalizedString)\("([^"]+)"',file.read_text(encoding='utf-8')))
for file in (root/'apps/host-settings').rglob('*.rs'):
 used.update(re.findall(r'\bt\("([^"]+)"', file.read_text(encoding='utf-8')))
for file in (root/'apps/desktop/src').rglob('*.cpp'):
 used.update(re.findall(r'\btext\("([^"]+)"', file.read_text(encoding='utf-8')))
if used != set(catalogs['en']):raise SystemExit(f'Locale key coverage differs: {used ^ set(catalogs["en"])}')
outputs={}
for lang,folder in [('en','en'),('zh-CN','zh-Hans')]:
 values=catalogs[lang]
 if not all(values.values()):raise SystemExit('Empty translation')
 for key,value in values.items():
  if re.findall(r'%(?:\.\d+)?[df@]',value) != re.findall(r'%(?:\.\d+)?[df@]',catalogs['en'][key]):raise SystemExit(f'Format arguments differ: {key}')
 outputs[root/f'apps/macos/Resources/{folder}.lproj/Localizable.strings']='// Generated from apps/desktop/locales.\n'+''.join(f'{json.dumps(k)} = {json.dumps(v,ensure_ascii=False)};\n' for k,v in sorted(values.items()))
# English fallback also works for standalone native test executables.
outputs[root/'apps/macos/Sources/Localization.swift']='''// Generated by scripts/generate-locales.py. Edit apps/desktop/locales instead.
import Foundation
func L(_ key: String, _ arguments: CVarArg...) -> String {
    let value = NSLocalizedString(key, value: englishStrings[key] ?? key, comment: "")
    return arguments.isEmpty ? value : String(format: value, locale: Locale.current, arguments: arguments)
}
private let englishStrings: [String:String] = [
'''+''.join(f'    {json.dumps(k)}: {json.dumps(v,ensure_ascii=False)},\n' for k,v in sorted(catalogs['en'].items()))+']\n'
for path,content in outputs.items():
 if '--check' in sys.argv:
  if not path.exists() or path.read_text(encoding='utf-8')!=content:raise SystemExit(f'Generated resource out of date: {path.relative_to(root)}')
 else:path.write_text(content,encoding='utf-8')
print(f'Validated {len(used)} shared bilingual keys and native resource parity')
